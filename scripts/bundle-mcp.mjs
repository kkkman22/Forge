#!/usr/bin/env node
/**
 * bundle-mcp.mjs — Bundle the tinkerman-context MCP server into a single
 * self-contained file for marketplace distribution.
 *
 * Why: the root .mcp.json points at the bundled server so that a
 * marketplace install (which copies the repo root but not node_modules)
 * can start the server with zero compilation and zero npm install —
 * "无需 git 或 Node.js 依赖管理" per the plugin install promise.
 *
 * The bundle inlines @modelcontextprotocol/sdk and zod. The SDK marks
 * ajv/ajv-formats as external (optional JSON-schema validation); these
 * are only loaded for a non-core validation path and the server starts
 * and registers all tools without them (verified by startup smoke test).
 *
 * Output: dist/tinkerman-context.mjs (git force-added; the rest of dist/ is
 * gitignored and regenerated on demand).
 *
 * Usage:
 *   node scripts/bundle-mcp.mjs            # build dist/tinkerman-context.mjs
 *   node scripts/bundle-mcp.mjs --check    # exit 1 if on-disk bundle is stale
 */
import { build } from "esbuild";
import { existsSync, readFileSync } from "node:fs";
import { resolve, join } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const ENTRY = join(ROOT, "dist", "src", "mcp", "server.js");
const OUTPUT = join(ROOT, "dist", "tinkerman-context.mjs");

function readVersion() {
  try {
    const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf-8"));
    return pkg.version ?? "unknown";
  } catch {
    return "unknown";
  }
}

async function buildBundle() {
  if (!existsSync(ENTRY)) {
    console.error(`✖ entry not found: ${ENTRY}`);
    console.error("  Run \`npx tsc\` first to compile src/mcp/server.ts → dist/src/mcp/server.js");
    process.exit(1);
  }

  const version = readVersion();
  const banner = `/*
 * tinkerman-context MCP server — bundled single-file build (v${version}).
 * Generated by scripts/bundle-mcp.mjs from src/mcp/server.ts.
 * Do not edit by hand; rebuild via \`node scripts/bundle-mcp.mjs\`.
 * Self-contained: inlines @modelcontextprotocol/sdk + zod.
 */`;

  await build({
    entryPoints: [ENTRY],
    bundle: true,
    packages: "bundle",
    platform: "node",
    format: "esm",
    target: "node20",
    outfile: OUTPUT,
    banner: { js: banner },
    // @modelcontextprotocol/sdk statically imports ajv/ajv-formats (declared as
    // its dependencies, present in node_modules). Bundle them in so the output
    // is truly self-contained — no node_modules needed at runtime.
    logLevel: "info",
    allowOverwrite: true,
  });

  console.log(`✓ bundled → ${OUTPUT}`);
}

async function check() {
  // Stale check: rebuild to a temp buffer and compare. esbuild is deterministic
  // for the same inputs, so a content diff means the committed bundle is stale.
  if (!existsSync(OUTPUT)) {
    console.error(`✖ ${OUTPUT} missing — run \`node scripts/bundle-mcp.mjs\``);
    process.exit(1);
  }
  // Re-run build then diff: simplest reliable signal. Must use the SAME banner
  // as buildBundle() — a divergent banner made the check always report stale.
  const version = readVersion();
  const banner = `/*
 * tinkerman-context MCP server — bundled single-file build (v${version}).
 * Generated by scripts/bundle-mcp.mjs from src/mcp/server.ts.
 * Do not edit by hand; rebuild via \`node scripts/bundle-mcp.mjs\`.
 * Self-contained: inlines @modelcontextprotocol/sdk + zod.
 */`;
  const before = readFileSync(OUTPUT, "utf-8");
  await build({
    entryPoints: [ENTRY],
    bundle: true,
    packages: "bundle",
    platform: "node",
    format: "esm",
    target: "node20",
    outfile: OUTPUT,
    banner: { js: banner },
    logLevel: "silent",
    allowOverwrite: true,
  });
  const after = readFileSync(OUTPUT, "utf-8");
  if (before.replace(/\s+$/, "") === after.replace(/\s+$/, "")) {
    console.log("✓ tinkerman-context bundle is fresh");
    process.exit(0);
  }
  console.error(`✖ ${OUTPUT} is stale — run \`node scripts/bundle-mcp.mjs\` and commit`);
  process.exit(1);
}

const mode = process.argv[2];
if (mode === "--check" || mode === "-c") {
  check().catch((err) => {
    console.error(err);
    process.exit(1);
  });
} else {
  buildBundle().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}

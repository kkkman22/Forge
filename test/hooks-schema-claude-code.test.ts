/**
 * Regression test: hooks.json must conform to the Claude Code hooks schema.
 *
 * Claude Code's /doctor validates every hook entry against a schema that
 * requires `{"type": "command", "command": "<shell string>"}`. The older
 * `{"args": [...]}` array form is NOT supported — it surfaces as
 * `hooks.<Event>.<n>.hooks.<n>.type: Invalid input` in /doctor and the hook
 * silently never fires.
 *
 * This test was added after a regression (v3.4.0 packaging) where 15 hook
 * entries in hooks/hooks.json used the unsupported `args` form and were copied
 * verbatim into user projects' .claude/settings.json by scripts/init.sh.
 *
 * Scope: hooks/hooks.json (the source of truth that init.sh copies into user
 * projects). The dist copies (dist-plugin/, dist/claude-code/bundles/) are
 * regenerated by build-dist.sh and smoke-tested separately.
 */
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";

const ROOT = resolve(import.meta.dirname, "..");
const hooksPath = resolve(ROOT, "hooks/hooks.json");
const hooksFile = JSON.parse(readFileSync(hooksPath, "utf-8"));

const hooksMap = hooksFile.hooks as Record<
  string,
  Array<{
    matcher?: string;
    hooks: Array<Record<string, unknown>>;
  }>
>;

// Claude Code supported hook events (superset — extras are tolerated, but
// every entry must be schema-valid).
const SUPPORTED_EVENTS = new Set([
  "SessionStart",
  "UserPromptSubmit",
  "PreToolUse",
  "PostToolUse",
  "Stop",
  "StopFailure",
  "PreCompact",
  "PostCompact",
  "TaskCompleted",
  "TaskCreated",
  "Notification",
  "SubagentStop",
  "TeammateIdle",
  "WorktreeCreate",
  "WorktreeRemove",
  "ConfigChange",
  "PermissionDenied",
]);

describe("Claude Code hooks schema: hooks/hooks.json", () => {
  const violations: string[] = [];

  for (const [eventName, groups] of Object.entries(hooksMap)) {
    if (!SUPPORTED_EVENTS.has(eventName)) {
      violations.push(`Unknown event "${eventName}" — not a Claude Code hook event`);
      continue;
    }

    for (let gi = 0; gi < groups.length; gi++) {
      const group = groups[gi];
      for (let hi = 0; hi < group.hooks.length; hi++) {
        const hook = group.hooks[hi];
        const loc = `${eventName}[${gi}].hooks[${hi}]`;

        // Every hook entry MUST have type: "command".
        if (hook.type !== "command") {
          violations.push(
            `${loc}: missing or wrong "type" (got ${JSON.stringify(hook.type)}). ` +
              `Claude Code requires {"type":"command"}.`,
          );
        }

        // The args-array form is NOT supported by Claude Code /doctor.
        if (hook.args !== undefined) {
          violations.push(
            `${loc}: uses unsupported "args" array form. ` +
              `Convert to {"type":"command","command":"<shell string>"}.`,
          );
        }

        // Every hook MUST have a command string.
        if (typeof hook.command !== "string" || hook.command.length === 0) {
          violations.push(
            `${loc}: missing or empty "command" string (got ${JSON.stringify(hook.command)}).`,
          );
        }
      }
    }
  }

  it("every hook entry uses {type:'command', command:'...'} — no args arrays", () => {
    expect(violations, violations.join("\n")).toEqual([]);
  });
});
